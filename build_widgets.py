"""Write widget-data.js from real results, so every widget on the tutorial page shows real Jev answers."""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).parent
SKIP = re.compile(r"(?i)hermes|nous|teknium|melkor")  # keep the source project off the page


def load(path):
    return json.loads((HERE / path).read_text())


def r2(x):
    return round(x, 2)


def find(rows, title_start):
    return next(r for r in rows if r["title"].startswith(title_start) and not SKIP.search(r["title"]))


# 1 · parse: the hand-written agent summaries, with Jev's real answer and the substring check
verdicts = [{"text": r["summary"], "jev": r2(r["noul"]), "substring": r["substring"], "done": r["truth"]}
            for r in load("cases/results/verdicts.json")["rows"]]

# 2 · gate: real pull requests and Jev's real answers to the three gate questions
gate_rows = load("cases/results/gate.json")["rows"]
gate = [
    {"label": label, "title": r["title"], "answers": {k: r2(v) for k, v in r["nouls"].items()}}
    for label, r in (
        ("Adds a catalog entry", find(gate_rows, "feat(plugin-catalog): add gemini-voice")),
        ("Corrects stale docs", find(gate_rows, "docs(mcp): correct stale")),
        ("Moves a token", find(gate_rows, "feat(plugins): core-made xAI Grok requests")),
        ("Changes a fail-closed default", find(gate_rows, "fix(toolsets): make zero tools expressible")),
        ("Fixes slash search", find(gate_rows, "fix(tui): rank an exact skill match")),
    )
]

# 3 · split: pull requests where Jev's own yes/no answers say both things are true
split_rows = [r for r in load("cases/results/split.json")["rows"]
              if min(r["nouls"].values()) >= 0.8 and not SKIP.search(r["title"])]
split_rows.sort(key=lambda r: min(r["choice"]["auth"], r["choice"]["no_tests"]))
buried = split_rows[0]  # the choice put nearly everything on one of two true things
even = min(split_rows, key=lambda r: abs(r["choice"]["auth"] - r["choice"]["no_tests"]))  # it split them down the middle
split = {
    "n_both": len(split_rows),
    "n_hurt": sum(min(r["choice"]["auth"], r["choice"]["no_tests"]) < 0.8 for r in split_rows),
    "examples": [{"title": r["title"], "nouls": {k: r2(v) for k, v in r["nouls"].items()},
                  "choice": {k: r2(v) for k, v in r["choice"].items()}} for r in (even, buried)],
}

# 4 · fan-out: measured median latency by questions per call, and the measured LLM classifier
fan = sorted({
    (1, load("cases/results/verdicts.json")["usage"]["ms_median"]),
    (3, load("cases/results/gate.json")["usage"]["ms_median"]),
    (load("cases/results/duplicates.json")["questions_per_call"], load("cases/results/duplicates.json")["usage"]["ms_median"]),
})
n8n = load("design/results/n8n.json")["rows"]
llm_ms = sorted(r["llm_ms"] for r in n8n)[len(n8n) // 2]

# 5 · confidence: one real choice answer to start the sliders from
wall = find(load("cases/results/split.json")["rows"], "feat(plugin-catalog): add wallaby-provider")
conf_start = {"title": wall["title"], "choice": {k: r2(v) for k, v in wall["choice"].items()}}

gate_q = load("cases/results/gate.json")["arms"]
data = {"verdicts": verdicts, "gate": gate, "gate_q": gate_q, "split": split,
        "fan": {"points": fan, "llm_ms": llm_ms}, "conf": conf_start}
(HERE / "widget-data.js").write_text("// Generated by build_widgets.py from */results/*.json. Do not edit.\nwindow.JEV = "
                                     + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print("wrote widget-data.js", {k: len(v) if isinstance(v, list) else "ok" for k, v in data.items()})
